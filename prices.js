// Typical price for a logged or stocked cigar, or null if it isn't in the Vault
function typicalPrice(brand, name) {
  const c = findCatalog(`${brand || ''} ${name || ''}`.trim()) || findCatalog(name || '');
  return c ? CATALOG_PRICES[c.b]?.[c.n] ?? null : null;
}
